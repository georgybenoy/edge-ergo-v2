_WELLNESS_DISCLAIMER = "General wellness reminder — not medical advice."


# ── Wellness Recommendations (PRD §33, §34) ───────────────────────────────────

def get_posture_recommendation(condition: str) -> Recommendation:
    """Retrieve specific actionable tip for a detected posture condition."""
    cond_clean = condition.strip().upper()
    return POSTURE_RECOMMENDATIONS.get(
        cond_clean,
        POSTURE_RECOMMENDATIONS["HIGH_RISK_POSTURE"],
    )


def get_movement_break_recommendation() -> Recommendation:
    """Movement break prompt framed as general workplace wellness (PRD §33, §34)."""
    return Recommendation(
        condition="MOVEMENT_BREAK",
        title="Movement Break Nudge",
        headline="Time for a brief movement pause",
        action_tip="Stand up, stretch your arms overhead, or take a short 1-minute walk to promote circulation.",
        disclaimer=_WELLNESS_DISCLAIMER,
    )


def get_hydration_recommendation() -> Recommendation:
    """Hydration reminder prompt framed as general workplace wellness (PRD §34)."""
    return Recommendation(
        condition="HYDRATION_REMINDER",
        title="Hydration Nudge",
        headline="Stay refreshed with water",
        action_tip="Drink a few sips of water to maintain focus and well-being during screen time.",
        disclaimer=_WELLNESS_DISCLAIMER,
    )


# Alias
get_break_recommendation = get_movement_break_recommendation
