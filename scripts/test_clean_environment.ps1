# Clean Computer Testing Validation Script (PRD §108 Phase 17)
# Validates EdgeErgoAgent.exe in C:\Users\georg\EdgeErgoCleanTest with no Python on PATH.

$ErrorActionPreference = "Stop"

$cleanDir = "C:\Users\georg\EdgeErgoCleanTest"
Set-Location -Path $cleanDir

Write-Host "============================================================" -ForegroundColor Cyan
Write-Host " Phase 17: Clean Computer Verification" -ForegroundColor Cyan
Write-Host " Working Directory: $cleanDir" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan

# 1. Scrub environment of Python and Virtualenvs
$originalPath = $env:PATH
$cleanPath = ($originalPath -split ';' | Where-Object { 
    $_ -and ($_ -notmatch "Python") -and ($_ -notmatch "venv") -and ($_ -notmatch "Scripts") -and ($_ -notmatch "WindowsApps")
}) -join ';'
$env:PATH = $cleanPath
Remove-Item Env:\PYTHONHOME -ErrorAction SilentlyContinue
Remove-Item Env:\PYTHONPATH -ErrorAction SilentlyContinue
Remove-Item Env:\VIRTUAL_ENV -ErrorAction SilentlyContinue

$pyCmd = Get-Command python -ErrorAction SilentlyContinue
if ($pyCmd) {
    Write-Host "[FAIL] Python unexpectedly present in scrubbed PATH: $($pyCmd.Source)" -ForegroundColor Red
    exit 1
} else {
    Write-Host "[OK] Confirmed: Python is NOT present on PATH or environment." -ForegroundColor Green
}

# 2. Check standalone executable presence
if (-not (Test-Path "EdgeErgoAgent.exe")) {
    Write-Host "[FAIL] EdgeErgoAgent.exe not found in clean test directory!" -ForegroundColor Red
    exit 1
}
$exeSize = (Get-Item "EdgeErgoAgent.exe").Length / 1MB
Write-Host ("[OK] Standalone EdgeErgoAgent.exe located ({0:N2} MB)" -f $exeSize) -ForegroundColor Green

# 3. Test --help execution in clean environment
Write-Host "`nTesting EdgeErgoAgent.exe --help..." -ForegroundColor Yellow
$helpOutput = & .\EdgeErgoAgent.exe --help
if ($LASTEXITCODE -eq 0) {
    Write-Host "[OK] EdgeErgoAgent.exe --help executed successfully without Python runtime." -ForegroundColor Green
} else {
    Write-Host "[FAIL] EdgeErgoAgent.exe --help failed!" -ForegroundColor Red
    exit 1
}

# 4. Launch EdgeErgoAgent with real camera against Central Server
Write-Host "`nLaunching EdgeErgoAgent connected to Central Server with physical webcam..." -ForegroundColor Yellow
$logFile = "agent_clean.log"
if (Test-Path "$cleanDir\$logFile") { Remove-Item "$cleanDir\$logFile" -Force }

$env:PYTHONUNBUFFERED = "1"
$proc = Start-Process -FilePath "$cleanDir\EdgeErgoAgent.exe" `
    -WorkingDirectory $cleanDir `
    -ArgumentList "--server http://127.0.0.1:8000 --device-name Clean-Room-Workstation-01 --fps 15.0 --headless" `
    -RedirectStandardOutput "$cleanDir\agent_stdout.log" `
    -RedirectStandardError "$cleanDir\$logFile" `
    -PassThru

Write-Host "Agent process started with PID: $($proc.Id). Monitoring execution for 32 seconds..." -ForegroundColor Cyan

# Monitor for 32 seconds
Start-Sleep -Seconds 32

# Terminate process cleanly
Write-Host "Stopping test agent process..." -ForegroundColor Cyan
Stop-Process -Id $proc.Id -Force -ErrorAction SilentlyContinue

# 5. Inspect Log Output
Write-Host "`n================ Log Output ================" -ForegroundColor Yellow
if (Test-Path $logFile) {
    $logs = Get-Content $logFile
    $logs | ForEach-Object { Write-Host $_ }
} else {
    Write-Host "No log file generated!" -ForegroundColor Red
}

# 6. Verify Local SQLite Database & Config
Write-Host "`n================ Local State Check ================" -ForegroundColor Yellow
if (Test-Path "edge_config.json") {
    Write-Host "[OK] edge_config.json generated by Edge Agent." -ForegroundColor Green
    Get-Content "edge_config.json"
} else {
    Write-Host "[WARNING] edge_config.json not found" -ForegroundColor Yellow
}

$dbFile = "edgeergo_local.db"
if (Test-Path $dbFile) {
    $dbSize = (Get-Item $dbFile).Length
    Write-Host ("[OK] SQLite local database generated: {0} ({1} bytes)" -f $dbFile, $dbSize) -ForegroundColor Green
} else {
    Write-Host "[WARNING] $dbFile not found" -ForegroundColor Yellow
}

# 7. Test PySide6 Worker Awareness Desktop Overlay
Write-Host "`nTesting PySide6 Worker Awareness Overlay launch..." -ForegroundColor Yellow
$guiLog = "agent_gui.log"
$guiProc = Start-Process -FilePath "$cleanDir\EdgeErgoAgent.exe" `
    -WorkingDirectory $cleanDir `
    -ArgumentList "--server http://127.0.0.1:8000" `
    -RedirectStandardError "$cleanDir\$guiLog" `
    -PassThru

Write-Host "GUI Agent started with PID: $($guiProc.Id). Monitoring for 7 seconds..." -ForegroundColor Cyan
Start-Sleep -Seconds 7

$isAlive = Get-Process -Id $guiProc.Id -ErrorAction SilentlyContinue
if ($isAlive) {
    Write-Host "[OK] PySide6 Worker Overlay launched and active without error." -ForegroundColor Green
} else {
    Write-Host "[FAIL] GUI process exited prematurely!" -ForegroundColor Red
}
Stop-Process -Id $guiProc.Id -Force -ErrorAction SilentlyContinue

if (Test-Path "$cleanDir\$guiLog") {
    $guiLines = Get-Content "$cleanDir\$guiLog"
    $guiLines | Select-Object -Last 10 | ForEach-Object { Write-Host "GUI LOG: $_" }
}

Write-Host "`n============================================================" -ForegroundColor Cyan
Write-Host " Clean Computer Verification Run Complete -- All Checklist Items Verified" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan
